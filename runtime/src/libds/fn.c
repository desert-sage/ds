#include "libds.h"
#include "fn.h"

ds_fn_slot_t ds_builtin_dispatch[DS_FN__MAX];

static ds_result_t reg(ds_builtin_fn_t op, ds_fn_t fn, bool rt_safe)
{
    if (!fn || op == DS_FN_UNSPECIFIED || (uint32_t) op >= (uint32_t) DS_FN__MAX)
        return DS_ERR_R(DS_ERR_INVAL, "ds_register_fn: bad op/fn");
    ds_builtin_dispatch[op].fn      = fn;
    ds_builtin_dispatch[op].rt_safe = rt_safe;
    return DS_OK_R;
}

ds_result_t ds_register_fn(ds_builtin_fn_t op, ds_fn_t fn)
{
    return reg(op, fn, false);
}

ds_result_t ds_register_fn_rt(ds_builtin_fn_t op, ds_fn_t fn)
{
    return reg(op, fn, true);
}

