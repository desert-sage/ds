:- type label
    --->    singular        % a singular message, or a message member of a oneof
    ;       repeated.

:- type shape
    --->    s_varint        % the integer types, bool and enum
    ;       s_fixed64       % double
    ;       s_len           % string
    ;       s_msg(message, label).

:- type walk
    --->    w_ok(bool)      % `yes`: an `Expr` past the limit was not read
    ;       w_undecodable
    ;       w_repeated
    ;       w_bad_string.

rdsc_11_4_judge(Root, R) = J :-
    walk(root_message(Root), R, -1, [], no, W),
    (
        W = w_undecodable,
        J = j_undecodable
    ;
        W = w_repeated,
        J = j_repeated
    ;
        W = w_bad_string,
        J = j_bad_string
    ;
        W = w_ok(Deep),
        (
            Deep = yes,
            J = j_too_deep
        ;
            Deep = no,
            J = j_decodes
        )
    ).

:- func root_message(judge_root) = message.

root_message(jr_alpha_node) = m_alpha_node.
root_message(jr_beta_node) = m_beta_node.
root_message(jr_terminal_node) = m_terminal_node.
root_message(jr_slot) = m_slot.

    % `Depth` is the nearest enclosing `Expr`'s, -1 outside every one. `Seen` holds
    % this message's singular message fields met so far.
    %
:- pred walk(message::in, reader::in, int::in, list(uint32)::in, bool::in,
             walk::out) is det.

walk(Msg, R0, Depth, Seen, Deep, Out) :-
    next_field(F, R0, R1),
    (
        F = fields_end,
        Out = w_ok(Deep)
    ;
        F = field_error(_),
        Out = w_undecodable
    ;
        F = field(Num, Value),
        ( if field_shape(Msg, Num, Shape) then
            judge_field(Msg, Num, Shape, Value, R1, Depth, Seen, Deep, Out)
        else
            walk(Msg, R1, Depth, Seen, Deep, Out)
        )
    ).

:- pred judge_field(message::in, uint32::in, shape::in, field_value::in,
                    reader::in, int::in, list(uint32)::in, bool::in, walk::out)
    is det.

judge_field(Msg, _, s_varint, Value, R1, Depth, Seen, Deep, Out) :-
    ( if Value = fv_varint(_) then
        walk(Msg, R1, Depth, Seen, Deep, Out)
    else
        Out = w_undecodable
    ).
judge_field(Msg, _, s_fixed64, Value, R1, Depth, Seen, Deep, Out) :-
    ( if Value = fv_fixed64(_) then
        walk(Msg, R1, Depth, Seen, Deep, Out)
    else
        Out = w_undecodable
    ).
judge_field(Msg, _, s_len, Value, R1, Depth, Seen, Deep, Out) :-
    ( if Value = fv_bytes(Bytes) then
        ( if reader_string(Bytes, _) then
            walk(Msg, R1, Depth, Seen, Deep, Out)
        else
            Out = w_bad_string
        )
    else
        Out = w_undecodable
    ).
judge_field(Msg, Num, s_msg(Sub, Label), Value, R1, Depth, Seen0, Deep0,
        Out) :-
    ( if Value = fv_bytes(Body) then
        ( if Label = singular, list.member(Num, Seen0) then
            Out = w_repeated
        else
            Seen = ( if Label = singular then [Num | Seen0] else Seen0 ),
            SubDepth = ( if Sub = m_expr then Depth + 1 else Depth ),
            ( if Sub = m_expr, SubDepth > max_expr_depth then
                % [RDSC.11.4]: nothing inside it is read.
                walk(Msg, R1, Depth, Seen, yes, Out)
            else
                walk(Sub, Body, SubDepth, [], no, SubOut),
                (
                    SubOut = w_ok(SubDeep),
                    walk(Msg, R1, Depth, Seen, bool.or(Deep0, SubDeep), Out)
                ;
                    SubOut = w_undecodable,
                    Out = SubOut
                ;
                    SubOut = w_repeated,
                    Out = SubOut
                ;
                    SubOut = w_bad_string,
                    Out = SubOut
                )
            )
        )
    else
        Out = w_undecodable
    ).

