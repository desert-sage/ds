% ds.dsc_judge -- a network body, or a `Slot`, judged before it is decoded
% ([RDSC.11.4]).
%
% `ds.dsc_expr`, `ds.dsc_action` and `ds.dsc_network` return the first refusal
% they meet, so this walk runs before them: it reads each field for its wire
% alone, and they run only on a body it passes. libds's `ds_pb_rdsc_11_4_judge`
% asks the same of the same bytes, with protobuf-c's descriptors where this has
% the generated tables below.
%
% A field the tables do not name is an unknown field. Every `s_len` field is a
% `string`, judged where it is met ([RDSC.9.12]).
%-----------------------------------------------------------------------------%

:- module ds.dsc_judge.
:- interface.

:- import_module ds.wire.

%-----------------------------------------------------------------------------%

:- type judge_root
    --->    jr_alpha_node
    ;       jr_beta_node
    ;       jr_terminal_node
    ;       jr_slot.
            % A `Slot`, for its conversions' `Expr`s ([RDSC.5.5.9]).

:- type judgement
    --->    j_decodes
    ;       j_undecodable
            % The bytes do not frame, or a field has the wrong wire type.
    ;       j_repeated
            % A singular message field met twice ([RDSC.9.5]).
    ;       j_bad_string
            % [RDSC.9.12].
    ;       j_too_deep.
            % Decodes down to the limit and holds an `Expr` nested deeper
            % ([RDSC.11.3]).

    % The first defect met answers; a decode defect anywhere the walk reads comes
    % before `j_too_deep`.
    %
:- func rdsc_11_4_judge(judge_root, reader) = judgement.

%-----------------------------------------------------------------------------%
:- implementation.

:- import_module ds.dsc_expr.
:- import_module bool.
:- import_module int.
:- import_module list.
:- import_module uint32.

%-----------------------------------------------------------------------------%

