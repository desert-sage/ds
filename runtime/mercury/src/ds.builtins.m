    ( if N = 0u32 then
        Reason = rf_unspecified
    else if ( N = 42u32 ; N = 43u32 ) then
        Reason = rf_belief
    else if N = 48u32 then
        Reason = rf_retired_verb
    else if ( N = 66u32 ; N = 67u32 ) then
        Reason = rf_case_mapping
    else if ( N = 85u32 ; N = 121u32 ) then
        Reason = rf_retired_interp
    else if ( N = 53u32 ; N = 77u32 ; N = 110u32 ) then
        Reason = rf_retired_record
    else if N = 80u32 then
        Reason = rf_retired_monotonic
    else if ( N = 109u32 ; N = 112u32 ) then
        Reason = rf_not_callable
    else
        Reason = rf_unallocated
    ).

