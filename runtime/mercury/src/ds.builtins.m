rdsc_4a_9_5_admits(Fn, N) :-
    Row = rdsc_4a_9_5_operands(Fn),
    (
        Row = rdsc_range(Min, Max),
        N >= Min,
        rdsc_4a_9_5_within(Max, N)
    ;
        Row = rdsc_pairs(Min, Max),
        N >= Min,
        rdsc_4a_9_5_within(Max, N),
        (N - Min) rem 2 = 0
    ).

:- pred rdsc_4a_9_5_within(rdsc_4a_9_5_max::in, int::in) is semidet.

rdsc_4a_9_5_within(rdsc_no_max, _).
rdsc_4a_9_5_within(rdsc_at_most(Max), N) :-
    N =< Max.

