"""check_libds_bu_complete.py — guard against libds.build drifting from the sources.

Python port of check-libds-bu-complete.sh (SPY1). Fails (non-zero) if a compilable
source, or a generated proto header a source #includes, has no declaration in
libds.build. This is the cost of explicit inputs without a Makefile wildcard (see
build_unit/PROPOSAL_glob.md): the drift that once shipped a partial libds.a — 6
sources + 3 protos silently absent — must not recur. Run as a stamp step
(libds.build) and in CI. NB: run on a clean tree (CI does); a warm build-unit cache can skip
it until libds.build changes — the glob feature (directory-as-input) is the full fix,
this is the cheap guard.

It lives in scripts/ with the other repo lints, and is one of the files there
the public tree keeps, because public libds.build runs it.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIBDS = ROOT / "runtime" / "src" / "libds"
# The graph that declares these sources: one graph for libds.a and the suites
# that test it, at the repository root. Every path in it is
# therefore root-relative, which is what `_ROOT_PREFIX` below strips back off
# to compare against LIBDS.
BUILDFILE = ROOT / "libds.build"
_ROOT_PREFIX = "runtime/src/libds/"
_INCLUDE = re.compile(r'#include "([A-Za-z0-9_]+)\.pb-c\.h"')
_GLOB_PATTERN = re.compile(r'pattern:\s*"([^"]+)"')
_DIR_EXT = re.compile(r"(?:(.+)/)?\*\.(cc?)")


def _graph() -> str:
    """libds.build's GRAPH: its step sugar expanded to the DS the patterns below
    read (`emit Glob pattern:`, `obj: "…"`, `emit Proto logical set: … stem:`).
    build-unit's expander is pure Python and ships in the harness wheel; a file
    without sugar expands to itself."""
    from build_unit.expand import expand
    return expand(BUILDFILE.read_text(), label="libds.build").text


def main() -> int:
    bu = _graph()
    rc = 0

    # 1. every hand-written source compiles into a declared Obj (generated *.pb-c.c
    #    excluded — those come from the protoc steps, checked in 2). A source dir that
    #    libds.build GLOBS (`emit Glob pattern: "<dir>/*.c"`, MKF1i) needs no explicit
    #    Obj: glob.expand desugars every *.c there, so drift is structurally impossible
    #    and there is nothing to enumerate — the glob IS the completeness for that dir.
    #
    #    Coverage is per (directory, extension): `*.c` and `*.cc` are DIFFERENT
    #    globs compiled by different rules, so a `.cc` in a directory globbed only
    #    for `.c` is not covered and must not be counted as such. That is why the
    #    key is a pair — REGEXRE2 added the top level's second language, and a
    #    directory-only key would have declared ds_re2.cc covered by `*.c`.
    #
    #    A pattern is ROOT-relative (`runtime/src/libds/rete/*.c`, and the top
    #    level's `runtime/src/libds/*.c`), while this guard walks LIBDS — so the
    #    prefix comes off here and the top level lands as the empty directory,
    #    which is what `rel.parent` gives a top-level source. Patterns outside
    #    runtime/src/libds (the suites' own sources) are not this guard's
    #    business and are skipped by the same test.
    globbed: set[tuple[str, str]] = set()
    for pat in _GLOB_PATTERN.findall(bu):
        if not pat.startswith(_ROOT_PREFIX):
            continue
        m = _DIR_EXT.fullmatch(pat[len(_ROOT_PREFIX):])
        if m:
            globbed.add((m.group(1) or "", m.group(2)))
    srcs = (sorted(LIBDS.glob("*.c")) + sorted(LIBDS.glob("*.cc"))
            + sorted(LIBDS.glob("rete/*.c")) + sorted(LIBDS.glob("series/*.c")))
    # dsc/, rfcs/ and reader/ keep explicit Obj rows because they mix in the
    # GENERATED *.pb-c.c. rfcs/ was missing from both scans below until the
    # reader group added a third such directory and the list was read.
    for d in ("dsc", "rfcs", "reader", "version"):
        srcs += [c for c in sorted(LIBDS.glob(f"{d}/*.c"))
                 if not c.name.endswith(".pb-c.c")]
    for c in srcs:
        rel = c.relative_to(LIBDS)
        d = str(rel.parent) if str(rel.parent) != "." else ""
        if (d, rel.suffix.lstrip(".")) in globbed:    # covered by a source glob
            continue
        o = str(rel)[: str(rel).rindex(".")] + ".o"
        if f'obj: "{o}"' not in bu:
            print(f"MISSING source: libds.build has no Obj (or covering Glob) for {o} ({rel})",
                  file=sys.stderr)
            rc = 1

    # 2. every generated proto header a source #includes is generated by libds.build.
    #    Checked against SET MEMBERSHIP, not a literal pathname. libds.build declares
    #    each protoc-c body set once as Proto facts and derives the five views from
    #    it — the argv, the Output, the protoc Consumes, the Obj, and the combine
    #    fan-in (GLOB1b) — so `pathname: "dsc/foo.pb-c.c"` no longer appears
    #    anywhere to match. Membership is also the stronger property: a stem in the
    #    set produces all five views or none, so this cannot pass while some other
    #    view is missing, which is what the five hand-written lists allowed.
    declared = set(re.findall(r'emit Proto logical set: "[a-z]+" stem: "([A-Za-z0-9_]+)"', bu))
    hdrs: set[str] = set()
    scan = list(LIBDS.glob("*.c")) + list(LIBDS.glob("*.cc")) + list(LIBDS.glob("*.h"))
    for d in ("rete", "dsc", "series", "rfcs", "reader"):
        scan += list((LIBDS / d).rglob("*.c")) + list((LIBDS / d).rglob("*.h"))
    for f in scan:
        hdrs.update(_INCLUDE.findall(f.read_text(errors="replace")))
    for h in sorted(hdrs):
        if h not in declared:
            print(f"MISSING proto: libds.build declares no Proto for {h} "
                  f"(a source #includes {h}.pb-c.h)", file=sys.stderr)
            rc = 1

    if rc == 0:
        print("libds.build complete: every source + generated proto is declared")
    return rc


if __name__ == "__main__":
    sys.exit(main())
