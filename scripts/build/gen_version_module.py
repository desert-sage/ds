"""Generate `ds.version.m` — this build's DS version, for Mercury.

[LDET.1.10]: DS carries one version and it is the DS version. Mercury's loader
accepts a `.dsc` iff its `compiler_version` shares this runtime's
`<major>.<minor>.` prefix, so it needs the same string libds gets from
-DDS_LIBDS_VERSION and the Python packages get from `__version__`. All of them
exec `scripts/build/ds-version.py`, which reads the repo-root VERSION file —
one derivation, no copies to keep in step.

GENERATED, NEVER COMMITTED. A checked-in constant would be a fourth home for a
number the release already owns, and nothing would go red when it drifted; that
is the arrangement this avoids, so it is not recreated here.
`runtime/mercury/src/ds.version.m` is gitignored.

PUBLIC, BESIDE `ds-version.py`, because every Mercury build needs it: the
public tree rebuilds the whole system, and
mercury.build's version step runs this for the runtime, the compiler, the
installable library, the release `dsc` and dap.toml's debug builds.

The PROVENANCE form, `<VERSION>+<sha>`, as libds and pyds embed: what it
writes depends on the commit, which is why the graph's step is never answered
from cache.

Run:  python3 scripts/build/gen_version_module.py [out_path]
      out_path defaults to runtime/mercury/src/ds.version.m
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "runtime" / "mercury" / "src" / "ds.version.m"


def ds_version() -> str:
    """The repo's DS version, or "" when there is no VERSION file.

    Empty is not an error: a VERSION-less checkout leaves every consumer at its
    own "0.0.0+dev" fallback, and those still AGREE. What must not happen is one
    consumer stamped and another not.
    """
    script = ROOT / "scripts" / "build" / "ds-version.py"
    if not script.exists():
        return ""
    r = subprocess.run([sys.executable, str(script), str(ROOT)],
                       capture_output=True, text=True, check=False)
    return r.stdout.strip() if r.returncode == 0 else ""


def render(version: str) -> str:
    return (
        "% SPDX-FileCopyrightText: 2026 Dan Finster and the Desert Sage Contributors\n"
        "% SPDX-License-Identifier: BSD-4-Clause OR AGPL-3.0-or-later\n"
        "% GENERATED by scripts/build/gen_version_module.py from the repo VERSION\n"
        "% file. Not committed; edit the VERSION file, not this.\n"
        "%\n"
        "% [LDET.1.10] -- the one version, and it is the DS version.\n"
        ":- module ds.version.\n"
        ":- interface.\n"
        "\n"
        "    % This build's DS version. The loader accepts an artefact iff its\n"
        "    % `compiler_version` begins with this string's `<major>.<minor>.`.\n"
        "    %\n"
        ":- func ds_version = string.\n"
        "\n"
        ":- implementation.\n"
        "\n"
        f'ds_version = "{version}".\n'
    )


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    v = ds_version() or "0.0.0+dev"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(v), encoding="utf-8")
    print(f"gen_version_module: {out} -> {v}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
